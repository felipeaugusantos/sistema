DROP FUNCTION IF EXISTS `fSaldoDisponivelGlobal`$$

CREATE DEFINER=`dbacitel`@`localhost` FUNCTION `fSaldoDisponivelGlobal`(strCodIte VARCHAR(10), strCodEmp CHAR(3)) RETURNS DECIMAL(14,2)
BEGIN

      RETURN IFNULL((SELECT SUM(IFNULL(G.ITE_SALDOS, 0) + IFNULL(G.ITE_QTEF_A, 0) + IFNULL(G.ITE_QTEF_F, 0) + IFNULL(G.ITE_QTEF_P, 0) - IFNULL(G.ITE_SALREG, 0) - IFNULL(G.ITE_SALREP, 0))
      
-- @SALDIS:=(G.ITE_SALDOS + IFNULL(ITE_QTEF_A, 0) + IFNULL(ITE_QTEF_F, 0) + IFNULL(ITE_QTEF_P, 0) - IFNULL(G.ITE_SALR_G, 0) - IFNULL(G.ITE_SALR_V, 0) - IFNULL(G.ITE_SALR_F, 0)) AS PRE_ESTDIS, --  "M - ESTOQUE DISPON?EL", -- CFG_CALSAL ??      
              FROM ITEGER G
              INNER JOIN PAREMP ON PAR_CODEMP = G.ITE_CODEMP AND PAR_CODITE = G.ITE_CODITE
              INNER JOIN CADITE C ON C.ITE_CODITE = G.ITE_CODITE
              LEFT JOIN AUTFOR ON G.ITE_CODEMP = AUT_CODEMP AND ITE_CODFOR = AUT_CODFOR
              WHERE IF(PAR_ORIITE = 'N' AND PAR_TIPEMP = 2 AND AUT_CODFOR IS NOT NULL, PAR_CODEMP , PAR_EMPGRU) = strCodEmp 
                AND G.ITE_CODITE = strCodIte), 0.00);
    END$$

DELIMITER ;