DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_IMO`$$

CREATE PROCEDURE `Insert_Contabilidade_IMO` () 
BEGIN
  INSERT CONLOG (
    LOG_TIPLAN,
    LOG_EMPLAN,
    LOG_TABELA,
    LOG_PROCES,
    LOG_INCDOC,
    LOG_MODLAN,
    LOG_STATUS
  ) 
  SELECT DISTINCT 
    "IMO",
    EMP_CODEMP,
    "IMOAMO",
    0,
    I.AUTOINCREM,
    1,
    NULL 
  FROM
    IMOAMO I 
    JOIN CADIMO 
      ON CADIMO.IMO_CODIMO = I.AMO_CODIMO 
    JOIN CADEMP 
      ON CADIMO.IMO_CODEMP = EMP_CODEMP 
  WHERE I.AMO_DTABAS = CURRENT_DATE ;
END $$

DELIMITER ;