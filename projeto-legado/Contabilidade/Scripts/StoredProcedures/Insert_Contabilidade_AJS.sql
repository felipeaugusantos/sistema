DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_AJS`$$

CREATE
    
    PROCEDURE `Insert_Contabilidade_AJS`()
  
    BEGIN
               INSERT CONLOG (LOG_TIPLAN, LOG_EMPLAN, LOG_TABELA, LOG_PROCES, LOG_INCDOC, LOG_MODLAN, LOG_STATUS)
               SELECT DISTINCT "AJS", GER_CODEMP, "MOVGER", 0, G.AUTOINCREM, 1, NULL
		 FROM MOVGER G
		 JOIN MOVDET D ON D.DET_SEQGER = G.AUTOINCREM
	        WHERE GER_DTAENT = CURRENT_DATE
                  AND LEFT(DET_CLAFIS, 1) >= "5" 
                  AND DET_ESPDOC = "AJ" 
                  AND DET_DTAFAT IS NULL
                UNION ALL 
               SELECT DISTINCT "AJS", GER_CODEMP, "NOTGER", 0, G.AUTOINCREM, 1, NULL
		 FROM NOTGER G
		 JOIN NOTDET D ON D.DET_SEQGER = G.AUTOINCREM
		WHERE GER_DTAENT = CURRENT_DATE
		  AND LEFT(DET_CLAFIS, 1) >= "5" 
                  AND DET_ESPDOC = "AJ" 
                  AND DET_DTAFAT IS NULL
                UNION ALL 
               SELECT DISTINCT "AJS", GER_CODEMP, "MOVGER", 0, G.AUTOINCREM, 2, NULL
		 FROM DEL_MOVGER G
		 JOIN DEL_MOVDET D ON D.DET_SEQGER = G.AUTOINCREM
	        WHERE G.DTADEL = CURRENT_DATE
                  AND LEFT(DET_CLAFIS, 1) >= "5" 
                  AND DET_ESPDOC = "AJ" 
                  AND DET_DTAFAT IS NULL
                UNION ALL
               SELECT DISTINCT "AJS", GER_CODEMP, "NOTGER", 0, G.AUTOINCREM, 2, NULL
		 FROM DEL_NOTGER G
		 JOIN DEL_NOTDET D ON D.DET_SEQGER = G.AUTOINCREM
		WHERE G.DTADEL = CURRENT_DATE
		  AND LEFT(DET_CLAFIS, 1) >= "5" 
                  AND DET_ESPDOC = "AJ" 
                  AND DET_DTAFAT IS NULL ;
    END$$

DELIMITER ;