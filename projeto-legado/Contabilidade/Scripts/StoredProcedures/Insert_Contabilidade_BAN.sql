DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_BAN`$$

CREATE PROCEDURE `Insert_Contabilidade_BAN` () 
BEGIN
  INSERT CONLOG (
    LOG_TIPLAN,
    LOG_EMPLAN,
    LOG_TABELA,
    LOG_PROCES,
    LOG_INCDOC,
    LOG_MODLAN,
    LOG_STATUS
  ) 
  SELECT DISTINCT 
    "BAN",
    CTB_CODEMP,
    "MOVBAN",
    0,
    M.AUTOINCREM,
    1,
    NULL 
  FROM
    MOVBAN M 
    LEFT JOIN CADPOR 
      ON POR_CODPOR = CTB_CODPOR 
    LEFT JOIN CFGSIS 
      ON SIS_CODEMP = CTB_CODEMP 
      AND SIS_CODCFG = 'CFG_MOVBAN' 
  WHERE CTB_DTALAN = CURRENT_DATE 
    AND IFNULL(CADPOR.POR_EXPAUT, "S") = "S" 
    AND IF(
      IFNULL(SIS_VALCFG, "N") = "S",
      TRUE,/*CTB_GERCON = 1*/
      TRUE
    ) 
  UNION
  ALL 
  SELECT DISTINCT 
    "BAN",
    CTB_CODEMP,
    "MOVBAN",
    0,
    M.AUTOINCREM,
    2,
    NULL 
  FROM
    DEL_MOVBAN M 
    LEFT JOIN CADPOR 
      ON POR_CODPOR = CTB_CODPOR 
    LEFT JOIN CFGSIS 
      ON SIS_CODEMP = CTB_CODEMP 
      AND SIS_CODCFG = 'CFG_MOVBAN' 
  WHERE M.DTADEL = CURRENT_DATE 
    AND IFNULL(CADPOR.POR_EXPAUT, "S") = "S" 
    AND IF(
      IFNULL(SIS_VALCFG, "N") = "S",
      TRUE, /*CTB_GERCON = 1*/
      TRUE
    ) ;
END $$

DELIMITER ;