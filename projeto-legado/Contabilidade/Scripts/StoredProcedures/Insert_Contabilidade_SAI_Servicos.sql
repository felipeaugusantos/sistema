DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_SAI_Servico`$$

CREATE PROCEDURE `Insert_Contabilidade_SAI_Servico`()
BEGIN
	INSERT CONLOG (LOG_TIPLAN, LOG_EMPLAN, LOG_TABELA, LOG_PROCES, LOG_INCDOC, LOG_MODLAN, LOG_STATUS)
		SELECT DISTINCT "SAI", FIS_CODEMP, "CADFIS", 0, F.AUTOINCREM, IF(FIS_HISTOR LIKE '%CANCELADO%', 2, 1) AS MODO, NULL
		  FROM CADFIS F
		 WHERE FIS_ENTSAI = "S" 
		   AND RIGHT(FIS_CLFSC1, 3) = "933" 
		   AND FIS_DTAENT = CURRENT_DATE  ;
    END$$

DELIMITER ;