DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_CTR` $$

CREATE PROCEDURE `Insert_Contabilidade_CTR` () 
BEGIN

  INSERT CONLOG (
    LOG_TIPLAN,
    LOG_EMPLAN,
    LOG_TABELA,
    LOG_PROCES,
    LOG_INCDOC,
    LOG_MODLAN,
    LOG_STATUS
  ) 
  SELECT DISTINCT 
    "CTR",
    IF(
      IFNULL(SIS_VALCFG, "N") = "S",
      CTR.CTR_EMPBAI,
      CTR.CTR_CODEMP
    ),
    "CADREC",
    0,
    CTR.AUTOINCREM,
    1,
    NULL 
  FROM
    CADREC CTR 
    LEFT JOIN CFGSIS 
      ON SIS_CODEMP = CTR_CODEMP 
      AND SIS_CODCFG = 'CTR_EMPBAI' 
  WHERE IFNULL(CTR.CTR_DTABAN, CTR.CTR_DTAREC) = CURRENT_DATE 
    AND CTR.CTR_ESPDOC <> 'CC' 
  UNION
  ALL 
  SELECT DISTINCT 
    "CTR",
    IF(
      IFNULL(SIS_VALCFG, "N") = "S",
      CTR.CTR_EMPBAI,
      CTR.CTR_CODEMP
    ),
    "CADREC",
    0,
    CTR.AUTOINCREM,
    2,
    NULL 
  FROM
    DEL_CADREC CTR 
    LEFT JOIN CFGSIS 
      ON SIS_CODEMP = CTR_CODEMP 
      AND SIS_CODCFG = 'CTR_EMPBAI' 
  WHERE CTR.DTADEL = CURRENT_DATE 
    AND CTR.CTR_ESPDOC <> 'CC' 
  UNION
  ALL 
  SELECT DISTINCT 
    "CTR",
    IF(
      IFNULL(SIS_VALCFG, "N") = "S",
      CTR.CTR_EMPBAI,
      CTR.CTR_CODEMP
    ),
    "CADREC",
    0,
    CTR.AUTOINCREM,
    2,
    NULL 
  FROM
    LOGCTR LCR 
    JOIN CADREC CTR 
      ON CTR.CTR_NUMDUP = LCR.CTR_NUMDUP 
      AND CTR.CTR_ESPDOC = LCR.CTR_ESPDOC 
      AND CTR.CTR_CODEMP = LCR.CTR_CODEMP 
      AND CTR.CTR_CODCLI = LCR.CTR_CODCLI 
      AND CTR.CTR_PARCEL = LCR.CTR_PARCEL 
      AND CTR.CTR_SEQBAI = LCR.CTR_SEQBAI 
    LEFT JOIN CFGSIS 
      ON SIS_CODEMP = LCR.CTR_CODEMP 
      AND SIS_CODCFG = 'CTR_EMPBAI' 
  WHERE LCR.CTR_DTALOG = CURRENT_DATE 
    AND LCR.CTR_ESPDOC <> 'CC' 
    AND LCR.CTR_DESCRI LIKE '%ESTORNO%'  ;

END $$
  
DELIMITER ;