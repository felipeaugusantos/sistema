DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_PCR` $$

CREATE PROCEDURE `Insert_Contabilidade_PCR` () 
BEGIN
  INSERT CONLOG (
    LOG_TIPLAN,
    LOG_EMPLAN,
    LOG_TABELA,
    LOG_PROCES,
    LOG_INCDOC,
    LOG_MODLAN,
    LOG_STATUS
  ) 
  SELECT DISTINCT 
    "PCR",
    CTR.CTR_CODEMP,
    "CADREC",
    0,
    CTR.AUTOINCREM,
    1,
    NULL 
  FROM
    CADREC CTR 
    LEFT JOIN CADCTA 
      ON CTA_CODCTA = CTR.CTR_CODCTA 
    LEFT JOIN DUPAGR AGR 
      ON AGR.CTR_NUMAGR = CTR.CTR_NUMDUP 
      AND AGR.CTR_EMPAGR = CTR.CTR_CODEMP 
      AND AGR.CTR_CODCLI = CTR.CTR_CODCLI 
    LEFT JOIN CADFIS 
      ON FIS_NUMDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_NUMDUP,
        CTR.CTR_NUMDUP
      ) 
      AND FIS_ESPDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_ESPDOC,
        CTR.CTR_ESPDOC
      ) 
      AND FIS_CODEMP = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_CODEMP,
        CTR.CTR_CODEMP
      ) 
      AND FIS_FORCLI = CTR.CTR_CODCLI 
      AND FIS_TIP_FC = "C" 
  WHERE CTA_PROCON = 1 
    AND CTR.CTR_DTACAD = CURRENT_DATE 
    AND CADFIS.AUTOINCREM IS NULL 
  UNION
  ALL 
  SELECT DISTINCT 
    "PCR",
    CTR.CTR_CODEMP,
    "CADREC",
    0,
    CTR.AUTOINCREM,
    2,
    NULL 
  FROM
    DEL_CADREC CTR 
    LEFT JOIN CADCTA 
      ON CTA_CODCTA = CTR.CTR_CODCTA 
    LEFT JOIN DUPAGR AGR 
      ON AGR.CTR_NUMAGR = CTR.CTR_NUMDUP 
      AND AGR.CTR_EMPAGR = CTR.CTR_CODEMP 
      AND AGR.CTR_CODCLI = CTR.CTR_CODCLI 
    LEFT JOIN CADFIS 
      ON FIS_NUMDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_NUMDUP,
        CTR.CTR_NUMDUP
      ) 
      AND FIS_ESPDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_ESPDOC,
        CTR.CTR_ESPDOC
      ) 
      AND FIS_CODEMP = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_CODEMP,
        CTR.CTR_CODEMP
      ) 
      AND FIS_FORCLI = CTR.CTR_CODCLI 
      AND FIS_TIP_FC = "C" 
  WHERE CTA_PROCON = 1 
    AND CTR.DTADEL = CURRENT_DATE 
    AND CADFIS.AUTOINCREM IS NULL 
  UNION
  ALL 
  SELECT DISTINCT 
    "PCR",
    CTR.CTR_CODEMP,
    "CADREC",
    0,
    CTR.AUTOINCREM,
    2,
    NULL 
  FROM
    LOGCTR LCR 
    JOIN CADREC CTR 
      ON CTR.CTR_NUMDUP = LCR.CTR_NUMDUP 
      AND CTR.CTR_ESPDOC = LCR.CTR_ESPDOC 
      AND CTR.CTR_CODEMP = LCR.CTR_CODEMP 
      AND CTR.CTR_CODCLI = LCR.CTR_CODCLI 
      AND CTR.CTR_PARCEL = LCR.CTR_PARCEL 
      AND CTR.CTR_SEQBAI = LCR.CTR_SEQBAI 
    LEFT JOIN CADCTA 
      ON CTA_CODCTA = CTR.CTR_CODCTA 
    LEFT JOIN DUPAGR AGR 
      ON AGR.CTR_NUMAGR = CTR.CTR_NUMDUP 
      AND AGR.CTR_EMPAGR = CTR.CTR_CODEMP 
      AND AGR.CTR_CODCLI = CTR.CTR_CODCLI 
    LEFT JOIN CADFIS 
      ON FIS_NUMDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_NUMDUP,
        CTR.CTR_NUMDUP
      ) 
      AND FIS_ESPDOC = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_ESPDOC,
        CTR.CTR_ESPDOC
      ) 
      AND FIS_CODEMP = IF(
        CTR.CTR_ESPDOC = "AG",
        AGR.CTR_CODEMP,
        CTR.CTR_CODEMP
      ) 
      AND FIS_FORCLI = CTR.CTR_CODCLI 
      AND FIS_TIP_FC = "C" 
  WHERE CTA_PROCON = 1 
    AND CADFIS.AUTOINCREM IS NULL 
    AND LCR.CTR_DTALOG = CURRENT_DATE 
    AND LCR.CTR_DESCRI LIKE '%ESTORNO%' ;
END $$

DELIMITER ;