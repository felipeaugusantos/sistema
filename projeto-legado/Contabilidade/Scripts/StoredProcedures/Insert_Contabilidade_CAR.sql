DELIMITER $$

DROP PROCEDURE IF EXISTS `Insert_Contabilidade_CAR`$$

CREATE PROCEDURE `Insert_Contabilidade_CAR` () 
BEGIN
  INSERT CONLOG (
    LOG_TIPLAN,
    LOG_EMPLAN,
    LOG_TABELA,
    LOG_PROCES,
    LOG_INCDOC,
    LOG_MODLAN,
    LOG_STATUS
  ) 
  SELECT DISTINCT 
    "CAR",
    MCA_CODEMP,
    "MOVCAR",
    0,
    M.AUTOINCREM,
    1,
    NULL 
  FROM
    MOVCAR M 
  WHERE MCA_DTAREC = CURRENT_DATE 
  UNION
  ALL 
  SELECT DISTINCT 
    "CAR",
    MCA_CODEMP,
    "MOVCAR",
    0,
    M.AUTOINCREM,
    2,
    NULL 
  FROM
    DEL_MOVCAR M 
  WHERE M.DTADEL = CURRENT_DATE 
 UNION ALL
   SELECT DISTINCT 
    "CAR",
    M.MCA_CODEMP,
    "MOVCAR",
    0,
    M.AUTOINCREM,
    2,
    NULL 
  FROM LOGMCA LMC
  JOIN MOVCAR M ON M.MCA_NUMDUP = LMC.MCA_NUMDUP
               AND M.MCA_CODCLI = LMC.MCA_CODCLI
               AND M.MCA_PARCEL = LMC.MCA_PARCEL
               AND M.MCA_CODEMP = LMC.MCA_CODEMP
 WHERE LMC.MCA_DESCRI LIKE '%ESTORNO%'
   AND LMC.MCA_DTALOG = CURRENT_DATE ;
END $$

DELIMITER ;