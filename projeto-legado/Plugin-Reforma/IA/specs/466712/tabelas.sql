-- Req. 466712 (REFTRI-01/REFTRI-02) - Tabelas do plugin libReformaPrecos.dll: IMPTRI, REFPRE (ampliada p/ tabelas 2 a 7), ITEREO, ITEREF,
-- REFCON e REFDIV. Script de referencia para o metodo do plugin que cria/ajusta as tabelas pela porta de gravacao
-- do host (IReformaGravacao: IniciarTransacao + ExecutarSql + Confirmar), fora de qualquer outra transacao (DDL no
-- MySQL confirma a transacao aberta) e com LOGREP (replica para as filiais).
--
-- Regras:
--  - MySQL 5.7: nao existe ADD COLUMN IF NOT EXISTS. Antes de cada ALTER, o metodo consulta information_schema.COLUMNS
--    e so executa o ALTER da coluna que falta (ver bloco 2b).
--  - Tipos de ITE_* abaixo sao os do ITEGER da base 2_30_74_150_COM (lidos em 2026-10-03). Eles variam por base
--    (ex.: ITE_TCIFCU e decimal(16,6) na 150 e decimal(12,6) na 2_30_74_XX_COM): na ITEREO/ITEREF o metodo deve usar o
--    COLUMN_TYPE do ITEGER do proprio banco e omitir a coluna que o ITEGER nao tiver (spec RN15).
--  - Sem chave estrangeira. Sem FOREIGN_KEY_CHECKS. Somente ASCII. CHARSET latin1.
-- =====================================================================================================================


-- ---------------------------------------------------------------------------------------------------------------------
-- 1. IMPTRI - aliquotas CBS/IBS/IS (1a linha). Igual ao que o plugin ja cria (Reforma.Aliquotas.Fonte).
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS IMPTRI (
  CBS   DECIMAL(5,2) DEFAULT NULL,
  IBS   DECIMAL(5,2) DEFAULT NULL,
  `IS`  DECIMAL(5,2) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

-- Aliquota de referencia so com a tabela vazia (idempotente).
INSERT INTO IMPTRI (CBS, IBS, `IS`)
SELECT 9.00, 1.00, 0.00 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM IMPTRI);


