-- ---------------------------------------------------------------------------------------------------------------------
-- 4. REFCON - controle da conversao: uma linha por conversao (CON_CHAVE) e empresa afetada.
--    CON_ORIGEM L/F; CON_OPCAO P (recalcular preco de venda) / M (recalcular margem);
--    CON_FASE P preparando / A aplicando / C concluida / D divergente. CON_CODOPE com o tipo de CADOPE.OPE_CODOPE.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS REFCON (
  CON_ID     BIGINT(20)   NOT NULL AUTO_INCREMENT,
  CON_CHAVE  CHAR(38)     NOT NULL,
  CON_CODEMP CHAR(3)      NOT NULL,
  CON_EMPORI CHAR(3)      NOT NULL,
  CON_ORIGEM CHAR(1)      NOT NULL,
  CON_OPCAO  CHAR(1)      NOT NULL,
  CON_FASE   CHAR(1)      NOT NULL,
  CON_CODOPE CHAR(3)      NOT NULL,
  CON_DTAINI DATE         NOT NULL,
  CON_HORINI TIME         NOT NULL,
  CON_DTAFIM DATE         NULL DEFAULT NULL,
  CON_HORFIM TIME         NULL DEFAULT NULL,
  CON_QTDITE INT(11)      NOT NULL DEFAULT 0,
  CON_QTDAPL INT(11)      NOT NULL DEFAULT 0,
  CON_QTDDIV INT(11)      NOT NULL DEFAULT 0,
  CON_ALQCBS DECIMAL(5,2) NULL DEFAULT NULL,
  CON_ALQIBS DECIMAL(5,2) NULL DEFAULT NULL,
  CON_ALQIS  DECIMAL(5,2) NULL DEFAULT NULL,
  CON_ORIIMP CHAR(1) NOT NULL DEFAULT 'T',
  CON_SOATIV CHAR(1) NOT NULL DEFAULT 'S',
  CON_MENSAG VARCHAR(255) NULL DEFAULT NULL,
  PRIMARY KEY (CON_ID),
  UNIQUE KEY UK_REFCON_01 (CON_CHAVE, CON_CODEMP),
  KEY IDX_REFCON_01 (CON_CODEMP)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;


